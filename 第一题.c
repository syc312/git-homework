// 第一题：遥控器数据判断与底盘状态控制
// 题目背景
// 调试 RoboMaster 步兵机器人时，遥控器的一个摇杆可以控制机器人前进和后退。

// 现在已经读取到遥控器的数据：
// int rc_value;
// 数据范围：
// -660 ~ 660
// 规定：
//	rc_value > 0      机器人前进
//	rc_value < 0      机器人后退
//	0			      机器人停止
// 
// 同时为了防止遥控器数据异常，规定：
// rc_value > 660
// 或者
// rc_value < -660
// 认为数据异常。
// 
// 任务
// 请补全下面程序。
// 要求：
// 1. 从键盘输入 rc_value。
// 2. 如果数据大于 660 或小于 -660，输出：遥控器数据异常
// 3. 如果数据正常：大于 0，输出 机器人前进； 小于 0，输出 机器人后退； 其他情况输出 机器人停止

// 下面为已有代码： 
#include <stdio.h>

int main()
{
    int rc_value = 0;

    printf("请输入遥控器数据：");

    /* 第1处：输入rc_value */
	scanf("%d",&rc_value);



    /* 第2处：判断数据是否超过正常范围 */
	if(rc_value>660||rc_value<-660)
	{
		printf("遥控器数据异常"); 
	}



    /* 第3处：数据正常时判断机器人状态 */
	if(rc_value>0&&rc_value<=660){
		printf("机器人前进"); 
	}if(rc_value<0&&rc_value>=-660){
		printf("机器人后退");
	}if(rc_value==0){printf("机器人停止");
	}




    return 0;
}

